/// `len` bytes of xorshift64 output: a stand-in for incompressible data that
/// is the same on every run and in the fixture's generator.
fn xorshift_bytes(seed: u64, len: usize) -> Vec<u8> {
    let mut x = seed;
    (0..len)
        .map(|_| {
            x ^= x << 13;
            x ^= x >> 7;
            x ^= x << 17;
            (x >> 32) as u8
        })
        .collect()
}

fn text() -> Vec<u8> {
    b"the quick brown fox jumps over the lazy dog\n".repeat(20)
}

/// Adler-32 (RFC 1950), with the modulus deferred across 5552-byte runs, which
/// is the largest run whose sums fit a `u32`.
fn adler32(data: &[u8]) -> u32 {
    let (mut a, mut b) = (1u32, 0u32);
    for run in data.chunks(5552) {
        for &byte in run {
            a += u32::from(byte);
            b += a;
        }
        a %= 65521;
        b %= 65521;
    }
    (b << 16) | a
}

/// A zlib stream of `plain` made of stored (uncompressed) DEFLATE blocks, split
/// at the 65535-byte block ceiling. It exists for the sizes where a fixture
/// would be too large to write out, and for the ceiling test; it is valid zlib,
/// not a shortcut around the decoder.
fn stored_zlib(plain: &[u8]) -> Vec<u8> {
    let mut out = vec![0x78, 0x01];
    let mut blocks: Vec<&[u8]> = plain.chunks(65535).collect();
    if blocks.is_empty() {
        blocks.push(&[]);
    }
    let last = blocks.len() - 1;
    for (i, block) in blocks.iter().enumerate() {
        out.push(u8::from(i == last)); // BFINAL in bit 0, BTYPE 00 (stored)
        let len = block.len() as u16;
        out.extend_from_slice(&len.to_le_bytes());
        out.extend_from_slice(&(!len).to_le_bytes());
        out.extend_from_slice(block);
    }
    out.extend_from_slice(&adler32(plain).to_be_bytes());
    out
}

/// What `Unpack::Zlib` makes of one frame: the bytes it left, or the message it
/// was refused with.
fn inflate(frame: &[u8]) -> Result<Vec<u8>, String> {
    let mut buf = frame.to_vec();
    Unpack::Zlib
        .frame(&mut buf)
        .map(|()| buf)
        .map_err(|e| e.to_string())
}

#[test]
fn an_empty_stream_gives_an_empty_frame() {
    assert_eq!(inflate(&EMPTY_ZLIB), Ok(Vec::new()));
}

#[test]
fn a_short_text_stream_gives_its_bytes() {
    assert_eq!(inflate(&ZLIB_HELLO).unwrap(), b"Hello there");
}

#[test]
fn a_repetitive_text_stream_gives_its_bytes() {
    assert_eq!(inflate(&TEXT_ZLIB), Ok(text()));
}

#[test]
fn random_bytes_at_two_sizes_come_back_unchanged() {
    assert_eq!(
        inflate(&RANDOM_300_ZLIB),
        Ok(xorshift_bytes(0x9E37_79B9_7F4A_7C15, 300))
    );
    // Past one stored block, so the stream carries two and the second is final.
    let plain = xorshift_bytes(0x0123_4567_89AB_CDEF, 70_000);
    assert_eq!(inflate(&stored_zlib(&plain)), Ok(plain));
}

#[test]
fn a_frame_of_exactly_the_ceiling_is_kept() {
    let plain = vec![0u8; LIMIT];
    assert_eq!(
        inflate(&stored_zlib(&plain)).map(|out| out.len()),
        Ok(LIMIT)
    );
}

#[test]
fn a_frame_one_byte_past_the_ceiling_is_refused() {
    let err = inflate(&stored_zlib(&vec![0u8; LIMIT + 1])).unwrap_err();
    assert!(err.contains("did not inflate"), "{err}");
    assert!(
        err.contains("limit"),
        "the refusal names the ceiling: {err}"
    );
}

#[test]
fn a_bad_zlib_header_is_refused() {
    let err = inflate(&[0x12, 0x34, 0x03, 0x00, 0, 0, 0, 1]).unwrap_err();
    assert!(err.contains("did not inflate"), "{err}");
}

#[test]
fn a_reserved_block_type_is_refused() {
    // BFINAL 1, BTYPE 11: the one block type RFC 1951 forbids.
    let err = inflate(&[0x78, 0x9c, 0x07, 0x00, 0x00, 0x00, 0x00, 0x01]).unwrap_err();
    assert!(err.contains("did not inflate"), "{err}");
}

#[test]
fn a_wrong_adler32_trailer_is_refused() {
    let mut bad = ZLIB_HELLO;
    let last = bad.len() - 1;
    bad[last] ^= 1;
    assert!(inflate(&bad).is_err());
}

#[test]
fn a_truncated_stream_is_refused_at_every_cut() {
    for cut in [0, 1, 2, 12, ZLIB_HELLO.len() - 1] {
        assert!(inflate(&ZLIB_HELLO[..cut]).is_err(), "cut at {cut}");
    }
}
